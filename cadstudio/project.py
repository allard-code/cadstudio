HOME = Path(os.environ.get("CADSTUDIO_HOME", Path.home() / "CADStudio"))
PROJECTS = HOME / "projects"
STATE_FILE = HOME / "state.json"
LOCK = threading.RLock()

# Kobra S1 build volume (mm)
BED = (250.0, 250.0, 250.0)

PALETTE = ["#F2F2F2", "#D62828", "#2A9D8F", "#F4A261", "#264653", "#E9C46A", "#8E44AD", "#111111"]

PART_DEFAULTS: dict[str, Any] = {
    "type": "code",
    "code": "",
    "color": "#F2F2F2",
    "filament": 1,
    "visible": True,
    "export": True,
    "location": [0, 0, 0, 0, 0, 0],  # x, y, z (mm), rx, ry, rz (degrees), applied after the code
    "scale": [1.0, 1.0, 1.0],  # sx, sy, sz, about the part's own centre, applied before location
    "mesh_file": None,
    "step_file": None,  # set for a "code" part generated by import_step(), so its cache key tracks the file's mtime
    "note": "",
    "plate": 1,  # build plate (bed) number, 1-based; location stays relative to that plate's centre
}

# Assembly ("Samenstel"): how the printed parts go together. Items are build123d code like parts (shared code,
# parameters and part() are available) but live outside the build plates: never exported, sliced or arranged.
ASSEMBLY_DEFAULTS: dict[str, Any] = {
    "code": "",
    "color": "#B0B7C3",
    "visible": True,
    "ghost": False,     # drawn see-through, so what's inside shows (e.g. the body shell)
    "explode": None,    # [dx, dy, dz] offset (mm) at explode factor 1; None = away from the assembly centre
    "note": "",
}

# Orca/Bambu lay plates out in a grid with a gap of 1/5 of the bed size between them (LOGICAL_PART_PLATE_GAP)
PLATE_GAP = 0.2
MAX_PLATES = 36

PART_REF = re.compile(r"""part\(\s*["']([^"']+)["']""")


class PartError(Exception):
    pass


def slugify(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_\- ]+", "", name).strip().replace(" ", "_")
    return s or "project"


def plate_columns(count: int) -> int:
    """Number of plate columns, same rule as Orca/Bambu (compute_colum_count): ceil-ish sqrt of the count."""
    v = math.sqrt(max(1, count))
    r = round(v)
    return int(r + 1 if v > r else r)


def plate_origin(plate: int, count: int) -> tuple[float, float]:
    """XY offset of plate N's centre relative to plate 1's centre, in the slicer's plate grid
    (columns to +X, rows to -Y, a gap of PLATE_GAP x bed size between plates)."""
    cols = plate_columns(count)
    i = max(1, int(plate)) - 1
    col, row = i % cols, i // cols
    return col * BED[0] * (1 + PLATE_GAP), -row * BED[1] * (1 + PLATE_GAP)


def _sha(obj: Any) -> str:
    return hashlib.sha1(json.dumps(obj, sort_keys=True, default=str).encode()).hexdigest()


