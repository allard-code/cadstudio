"""send_to_printer against a fake Home Assistant (file upload + event)."""
import json
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer

import pytest

from cadstudio import homeassistant as HA
from cadstudio import mcp_server as M

GCODE = """; generated by OrcaSlicer
; estimated printing time (normal mode) = 34m 50s
G1 X0 Y0
; total filament used [g] = 14.70
; CONFIG_BLOCK_START
; filament_type = PLA;PETG
; CONFIG_BLOCK_END
"""


@pytest.fixture
def fake_ha(monkeypatch):
    seen = {"uploads": [], "events": []}

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        def do_POST(self):  # noqa: N802
            body = self.rfile.read(int(self.headers["Content-Length"]))
            if self.headers.get("Authorization") != "Bearer secret":
                self.send_response(401)
                self.end_headers()
                return
            if self.path == "/api/file_upload":
                assert self.headers["Content-Type"].startswith("multipart/form-data; boundary=")
                seen["uploads"].append(body)
                out = {"file_id": "abc123"}
            elif self.path.startswith("/api/events/"):
                seen["events"].append((self.path.rsplit("/", 1)[1], json.loads(body)))
                out = {"message": "Event fired."}
            else:
                self.send_response(404)
                self.end_headers()
                return
            data = json.dumps(out).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

    srv = HTTPServer(("127.0.0.1", 0), Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    monkeypatch.setenv("CADSTUDIO_HA_URL", f"http://127.0.0.1:{srv.server_port}")
    monkeypatch.setenv("CADSTUDIO_HA_TOKEN", "secret")
    monkeypatch.delenv("CADSTUDIO_HA_EVENT", raising=False)
    yield seen
    srv.shutdown()


def test_gcode_materials(tmp_path):
    p = tmp_path / "x.gcode"
    p.write_text(GCODE)
    assert HA.gcode_materials(p) == ["PLA", "PETG"]
    p.write_text("G1 X0\n")
    assert HA.gcode_materials(p) == []


def test_send_to_printer_needs_config(proj, monkeypatch):
    monkeypatch.delenv("CADSTUDIO_HA_URL", raising=False)
    monkeypatch.delenv("CADSTUDIO_HA_TOKEN", raising=False)
    res = M.send_to_printer(1)
    assert not res["ok"] and "CADSTUDIO_HA_URL" in res["error"]


def test_send_to_printer_needs_a_slice(proj, fake_ha):
    res = M.send_to_printer(1)
    assert not res["ok"] and "slice_plate" in res["error"]


def test_send_to_printer_uploads_and_fires_event(proj, fake_ha):
    gcode = proj.dir / "exports" / f"{proj.name}-plate1.gcode"
    gcode.parent.mkdir(parents=True, exist_ok=True)
    gcode.write_text(GCODE)
    res = M.send_to_printer(1)
    assert res["ok"], res
    assert res["file_id"] == "abc123" and res["event"] == "cadstudio_print_request"
    assert len(fake_ha["uploads"]) == 1 and b"filament_type = PLA;PETG" in fake_ha["uploads"][0]
    assert f'filename="{gcode.name}"'.encode() in fake_ha["uploads"][0]
    (event, data), = fake_ha["events"]
    assert event == "cadstudio_print_request"
    assert data == {"file_id": "abc123", "filename": gcode.name, "project": proj.name, "plate": 1,
                    "material": "PLA", "materials": ["PLA", "PETG"], "print_time": "34m 50s", "filament_g": 14.7}


def test_bad_token_gives_a_clear_error(proj, fake_ha, monkeypatch):
    monkeypatch.setenv("CADSTUDIO_HA_TOKEN", "wrong")
    gcode = proj.dir / "exports" / f"{proj.name}-plate1.gcode"
    gcode.parent.mkdir(parents=True, exist_ok=True)
    gcode.write_text(GCODE)
    res = M.send_to_printer(1)
    assert not res["ok"] and "401" in res["error"] and "CADSTUDIO_HA_TOKEN" in res["error"]
